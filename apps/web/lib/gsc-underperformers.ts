// Zona + genero tal como salian en la URL de GSC: mezcla de slug moderno y
// nombre legacy sin normalizar (ver resolveGenre en zone-genre-page.tsx, que
// acepta las dos formas). Se normalizan aqui mismo para poder compararlas
// contra el zone/genreSlug(genre) que ya calcula la pagina.
function normalizeZoneGenreKey(zone: string, genre: string) {
  let decoded = genre
  try { decoded = decodeURIComponent(genre) } catch {}
  const slug = decoded
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
  return `${zone.toLowerCase()}/${slug}`
}

